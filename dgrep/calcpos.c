/**********************************************************************
 *
 *	calcpos
 */
bool calcpos(regbuf_t* rb)
{
	rb->setsize = set_bytesize(rb->root+1);
	if (!set_pos(rb) || !followpos(rb)) {
		free_posmem(rb);
		return FALSE;
	}
#ifdef TEST
	if (debug > 1) {
		print_tree(rb);
		print_followpos(rb);
	}
#endif
	free_posmem(rb);
	return TRUE;
}
